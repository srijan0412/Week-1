class AverageMarks {
	public static void main(String[] args) {
		
		//Name of the person
		String name = "Sam";
		
		//Scores in PCM : 
		int mathsScore = 94, physicsScore = 95, chemistryScore = 96;
		
		//Calculation of average
		double average = (mathsScore + physicsScore + chemistryScore)/3;
		
		System.out.println(name + "'s average mark in PCM is " + average);
		
	}
}